// @vitest-environment jsdom
import '@testing-library/jest-dom/vitest'
import { afterEach, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, act } from '@testing-library/react'
import { App } from '../../src/app/App'
import { createAppCatalog } from '../../src/app/catalog'
import { createParameterStore } from '../../src/app/parameter-workspace'
afterEach(() => { cleanup(); vi.useRealTimers() })
it('loads, plays fixed steps, pauses on force input, reinitializes and restores the baseline', () => {
  vi.useFakeTimers()
  const store = createParameterStore()
  render(<App store={store} catalog={createAppCatalog()} />)
  fireEvent.click(screen.getByRole('button', { name: 'Load C2 example' }))
  expect(store.getSnapshot().state.loads.pitchMoment).toMatchObject({ value: 600 })
  fireEvent.click(screen.getByRole('button', { name: 'Play pitch' }))
  act(() => { vi.advanceTimersByTime(100) })
  expect(store.getSnapshot().state.simulation.elapsedTime).toMatchObject({ value: 0.1 })
  fireEvent.change(screen.getByLabelText('Tail force (+ down)'), { target: { value: '0' } })
  fireEvent.click(screen.getByRole('button', { name: 'Set Tail force (+ down)' }))
  expect(store.getSnapshot().state.simulation.status).toBe('paused')
  expect(store.getSnapshot().state.loads.pitchMoment).toMatchObject({ value: -750 })
  fireEvent.click(screen.getByRole('button', { name: 'Reinitialize pitch' }))
  expect(store.getSnapshot().state.motion.pitch).toMatchObject({ value: 0 })
  fireEvent.click(screen.getByRole('button', { name: 'Reset scenario' }))
  expect(store.getSnapshot().state.modules.controls?.tailForce).toMatchObject({ value: 450 })
  fireEvent.click(screen.getByRole('button', { name: 'Return to empty workspace' }))
  expect(store.getSnapshot().state.simulation.status).toBe('unconfigured')
})
it('C3 numeric elevator edits update the shared command and aerodynamic readouts', () => {
  const store = createParameterStore()
  render(<App store={store} catalog={createAppCatalog()} />)
  fireEvent.click(screen.getByRole('button', { name: 'Load C3 elevator example' }))
  const input = screen.getByLabelText('Elevator (deg)')
  fireEvent.change(input, { target: { value: '5' } })
  fireEvent.click(screen.getByRole('button', { name: 'Set Elevator (deg)' }))
  expect(store.getSnapshot().state.controls.elevatorCommanded).toMatchObject({ value: Math.PI / 36 })
  const moment = store.getSnapshot().state.outputs.controls?.deltaMoment
  expect(moment?.status === 'known' && moment.value).toBeCloseTo(-1642.005760276)
  fireEvent.click(screen.getByRole('button', { name: 'Elevator plots' }))
  expect(screen.getByRole('img', { name: 'Elevator moment versus speed' })).toBeVisible()
  fireEvent.click(screen.getByRole('button', { name: 'Reset scenario' }))
  expect(store.getSnapshot().state.motion.airspeed).toMatchObject({ value: 40 })
})
it('rejects invalid airspeed locally, restores active value, and keeps plot scales fixed', () => {
  const store = createParameterStore()
  render(<App store={store} catalog={createAppCatalog()} />)
  fireEvent.click(screen.getByRole('button', { name: 'Load C3 elevator example' }))
  const input = screen.getByLabelText('Airspeed (m/s)')
  const before = store.getSnapshot()
  fireEvent.change(input, { target: { value: '-10' } })
  fireEvent.click(screen.getByRole('button', { name: 'Set Airspeed (m/s)' }))
  expect(input).toHaveValue(40)
  expect(screen.getByRole('alert')).toHaveTextContent('Active value restored')
  expect(store.getSnapshot()).toBe(before)
  fireEvent.click(screen.getByRole('button', { name: 'Elevator plots' }))
  const plot = screen.getByRole('img', { name: 'Elevator moment versus angle' })
  expect(plot).toHaveAttribute('data-scale', '15000')
  fireEvent.change(input, { target: { value: '80' } })
  fireEvent.click(screen.getByRole('button', { name: 'Set Airspeed (m/s)' }))
  expect(plot).toHaveAttribute('data-scale', '15000')
  expect(screen.getAllByLabelText('Current operating point')).toHaveLength(2)
  expect(screen.queryByRole('slider', { name: 'elevator deflection slider' })).not.toBeInTheDocument()
})
