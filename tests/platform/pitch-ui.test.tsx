it('C4 applies the nominal target through the store and keeps rate planning separate from playback', () => {
  const store = createParameterStore()
  render(<App store={store} catalog={createAppCatalog()} />)
  fireEvent.click(screen.getByRole('button', { name: 'Load C4 authority example' }))
  expect(screen.getByRole('button', { name: 'Play pitch' })).not.toBeVisible()
  fireEvent.click(screen.getByRole('button', { name: 'Use nominal target deflection' }))
  expect(store.getSnapshot().state.outputs.controls?.achievedAcceleration).toMatchObject({ status: 'known' })
  expect(screen.getByText('Selected deflection meets the target in the nominal model.')).toBeVisible()
  const result = store.getSnapshot().state.outputs.controls?.achievedAcceleration
  expect(result?.status === 'known' && result.value).toBeCloseTo(0.12)
  fireEvent.click(screen.getByRole('button', { name: 'Rate plan' }))
  expect(screen.getByText(/does not drive elevator motion/)).toBeVisible()
  const before = store.getSnapshot().state.controls.elevatorCommanded
  fireEvent.change(screen.getByLabelText('Planning start pose'), { target: { value: '2' } })
  fireEvent.click(screen.getByRole('button', { name: 'Set Planning start pose' }))
  expect(store.getSnapshot().state.controls.elevatorCommanded).toEqual(before)
  fireEvent.click(screen.getByRole('button', { name: 'Elevator plots' }))
  expect(screen.getByRole('img', { name: 'Elevator authority versus deflection' })).toHaveAttribute('data-scale', '5000')
  fireEvent.click(screen.getByLabelText('Compare uncertainty band'))
  expect(document.querySelector('[aria-label="Bounded effectiveness uncertainty"]')).not.toBeNull()
  fireEvent.click(screen.getByLabelText('Show separate rate-plan interval'))
  expect(document.querySelector('[aria-label="Separate planning reachable interval"]')).not.toBeNull()
})
